#!/usr/bin/env node
// OSM XML extract -> compact building data for one area of the Coney map (src/world/coney/osm-neptune.js by default).
// Usage: node tools/import-osm-area.mjs <map.osm> [out.js] [x0,z0,x1,z1]
// Same frame as qa/tools/osm-coney.py: metres, origin 40.5745 N -73.9800 W, rotated 8.33 deg onto the street grid, +z = ocean.
// Output: OSM-derived (ODbL); no names are emitted (de-branding rule), tags only pick styles.
import fs from 'node:fs';

const [src, out = 'src/world/coney/osm-neptune.js', bboxArg = '380,-800,800,-430'] = process.argv.slice(2);
if (!src) { console.error('usage: node tools/import-osm-area.mjs <map.osm> [out.js] [x0,z0,x1,z1]'); process.exit(1); }
const [BX0, BZ0, BX1, BZ1] = bboxArg.split(',').map(Number);
const LAT0 = 40.5745, LON0 = -73.98, KX = 111320 * Math.cos(LAT0 * Math.PI / 180), KY = 110540, TH = 8.33 * Math.PI / 180;
const r1 = (v) => Math.round(v * 10) / 10;
export function project(lat, lon) { const x = (lon - LON0) * KX, z = -(lat - LAT0) * KY; return [r1(x * Math.cos(TH) - z * Math.sin(TH)), r1(x * Math.sin(TH) + z * Math.cos(TH))]; }

const LEVEL_H = 3.0;   // m per storey when only building:levels is mapped
const DEFAULT_H = { house: 8, detached: 8, semidetached_house: 8, terrace: 9, apartments: 12, residential: 9, retail: 5, commercial: 6, garage: 3, garages: 3, shed: 3, industrial: 7, warehouse: 7, service: 4, church: 12, school: 12 };
const FALLBACK_H = 7;   // building=yes with nothing else
const MIN_AREA = 12;    // m2: drop slivers
const SKIP = new Set(['roof', 'construction', 'canopy', 'carport']);

const xml = fs.readFileSync(src, 'utf8');
const nodes = new Map();
for (const m of xml.matchAll(/<node id="(\d+)"[^>]*?lat="([-\d.]+)" lon="([-\d.]+)"/g)) nodes.set(m[1], [+m[2], +m[3]]);
const tagsOf = (body) => { const t = {}; for (const m of body.matchAll(/<tag k="([^"]+)" v="([^"]*)"\/>/g)) t[m[1]] = m[2]; return t; };
const ways = new Map(), buildings = [], parts = [];
const area = (Q) => Math.abs(Q.reduce((s, a, i) => { const b = Q[(i + 1) % Q.length]; return s + a[0] * b[1] - b[0] * a[1]; }, 0)) / 2;
const heightOf = (t) => {
  const h = parseFloat(String(t.height || '').split(' ')[0]); if (h > 0) return { h, from: 'height' };
  const lv = parseFloat(t['building:levels']); if (lv > 0) return { h: lv * LEVEL_H, from: 'levels' };
  return { h: DEFAULT_H[t.building] ?? FALLBACK_H, from: 'default' };
};
function emit(ring, t) {
  const part = t['building:part'] && t['building:part'] !== 'no' ? t['building:part'] : null, kind = part || t.building;
  if (!kind || SKIP.has(kind) || kind === 'no') return;
  let Q = ring.map((id) => nodes.get(id)); if (Q.some((p) => !p)) return;
  Q = Q.map(([la, lo]) => project(la, lo)); if (Q.length > 3 && Q[0][0] === Q.at(-1)[0] && Q[0][1] === Q.at(-1)[1]) Q.pop();
  if (Q.length < 3 || area(Q) < MIN_AREA) return;
  const cx = Q.reduce((s, q) => s + q[0], 0) / Q.length, cz = Q.reduce((s, q) => s + q[1], 0) / Q.length;
  if (cx < BX0 || cx > BX1 || cz < BZ0 || cz > BZ1) return;
  const { h, from } = heightOf({ ...t, building: kind }), e = { p: Q, h: r1(h), t: kind };
  const mh = parseFloat(t.min_height) || (parseFloat(t['building:min_level']) || 0) * LEVEL_H; if (part && mh > 0) e.mh = r1(mh);
  if (from === 'default') e.hd = 1;
  if (t.shop || t.amenity) e.u = t.shop ? 'shop:' + t.shop : 'amenity:' + t.amenity;
  if (t['roof:shape']) e.rs = t['roof:shape'];
  if (t['building:levels']) e.lv = +t['building:levels'];
  (part ? parts : buildings).push(e);
}
for (const m of xml.matchAll(/<way id="(\d+)"[^>]*>([\s\S]*?)<\/way>/g)) {
  const ring = [...m[2].matchAll(/<nd ref="(\d+)"\/>/g)].map((n) => n[1]); ways.set(m[1], ring);
  emit(ring, tagsOf(m[2]));
}
let rel = 0;
for (const m of xml.matchAll(/<relation id="(\d+)"[^>]*>([\s\S]*?)<\/relation>/g)) {
  const t = tagsOf(m[2]); if (!t.building || t.type !== 'multipolygon') continue;
  for (const o of m[2].matchAll(/<member type="way" ref="(\d+)" role="outer"\/>/g)) if (ways.get(o[1])) { emit(ways.get(o[1]), t); rel++; }
}
for (const L of [buildings, parts]) L.sort((a, b) => a.p[0][0] - b.p[0][0] || a.p[0][1] - b.p[0][1]);   // stable output across OSM id churn
const js = `// GENERATED by tools/import-osm-area.mjs from OpenStreetMap data (c) OpenStreetMap contributors, ODbL 1.0
// (https://www.openstreetmap.org/copyright). Do not edit by hand; rerun the tool on a fresh extract instead.
// The blocks round the F el's Neptune Av station. Frame: the map's (qa/tools/osm-coney.py). Bbox x ${BX0}..${BX1}, z ${BZ0}..${BZ1}.
// b: buildings {p footprint, h metres (height, else levels x ${LEVEL_H}, else a default by type: hd 1), t building tag,
// u shop / amenity, rs roof:shape, lv levels}; pt: building:part pieces, same fields + mh (min height), which stand in for
// the outline they sit in (a 3D renderer draws the parts, not the outline).
export const NEPTUNE_BBOX = ${JSON.stringify({ x0: BX0, z0: BZ0, x1: BX1, z1: BZ1 })};
export const NEPTUNE = ${JSON.stringify({ b: buildings, pt: parts })};
`;
fs.writeFileSync(out, js);
const by = {}; for (const b of buildings) by[b.t] = (by[b.t] || 0) + 1;
console.log(`${buildings.length} buildings, ${parts.length} parts (${rel} relation rings, ${buildings.filter((b) => !b.hd).length} with height or levels) -> ${out}`, by);
